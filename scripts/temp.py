def resolve_head(repo: str) -> str:
    """Resolve the current HEAD commit without cloning the repository."""

    result = subprocess.run(
        ["git", "ls-remote", repo, "HEAD"],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )

    if result.returncode != 0:
        raise RuntimeError(
            f"Could not resolve {repo}\n"
            f"stderr:\n{result.stderr}"
        )

    line = result.stdout.strip()

    if not line:
        raise RuntimeError(f"No HEAD returned for {repo}")

    sha = line.split()[0]

    if len(sha) != 40:
        raise RuntimeError(
            f"Unexpected commit SHA for {repo}: {sha}"
        )

    return sha


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)

    resolved: list[tuple[str, str, str, str]] = []

    print("Resolving Rust baseline repositories...\n")

    for index, (name, repo, package) in enumerate(CRATES, start=1):
        print(f"[{index:02}/{len(CRATES)}] {name:<20}", end="", flush=True)

        sha = resolve_head(repo)

        print(f" {sha[:12]}")
        resolved.append((name, repo, package, sha))

    lines = [
        "# Rust systems-library safety baseline",
        "#",
        "# Generated by scripts/make_rust_baseline_config.py.",
        "# Every repository is pinned to the exact HEAD commit that was",
        "# observed when this file was generated.",
        "#",
        "# Commit this file if the scan will be used as research data.",
        "",
        'workspace_root = "../.rust-baseline-work"',
        'results_root = "../results/rust-baseline"',
        "",
    ]

    categories = {
        "redb": "Storage / Database",

        "rkyv": "Serialization / Zero-copy / Buffers",
        "bytes": "Serialization / Zero-copy / Buffers",
        "serde": "Serialization / Zero-copy / Buffers",
        "prost": "Serialization / Zero-copy / Buffers",

        "tokio": "Async Runtime / Networking / Protocols",
        "mio": "Async Runtime / Networking / Protocols",
        "quinn-proto": "Async Runtime / Networking / Protocols",
        "rustls": "Async Runtime / Networking / Protocols",
        "hyper": "Async Runtime / Networking / Protocols",
        "tonic": "Async Runtime / Networking / Protocols",
        "tower": "Async Runtime / Networking / Protocols",

        "crossbeam-epoch": "Concurrency",
        "rayon": "Concurrency",
        "parking_lot": "Concurrency",

        "rustix": "Low-level / OS / Data Structures / Performance",
        "hashbrown": "Low-level / OS / Data Structures / Performance",
        "blake3": "Low-level / OS / Data Structures / Performance",
    }

    previous_category: str | None = None

    for name, repo, package, sha in resolved:
        category = categories[name]

        if category != previous_category:
            lines.extend(
                [
                    "",
                    "# ============================================================",
                    f"# {category}",
                    "# ============================================================",
                    "",
                ]
            )
            previous_category = category

        lines.extend(
            [
                "[[crate]]",
                f'name = "{name}"',
                f'repo = "{repo}"',
                f'rev = "{sha}"',
                f'package = "{package}"',
                "",
            ]
        )

    temp = OUTPUT.with_suffix(".toml.tmp")
    temp.write_text("\n".join(lines), encoding="utf-8")
    temp.replace(OUTPUT)

    print()
    print(f"Wrote {OUTPUT}")
    print()
    print("Next:")
    print(
        "python -m rust_baseline.cli validate-config "
        "--config configs/rust-baseline.toml"
    )


if __name__ == "__main__":
    main()